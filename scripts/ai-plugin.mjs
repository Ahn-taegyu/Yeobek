import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { z } from "zod";

const root = new URL("../ai/yeobek/", import.meta.url);
const target = new URL("../src/lib/ai/plugin.generated.ts", import.meta.url);
const names = ["retrieve-wiki", "speak-docent", "draft-narration", "organize-artist", "evaluate-narration", "ops-notify", "support-reply", "author-qa", "read-material"];
const tools = ["support.read", "status.read", "voice.read", "voice.store", "voice.reserve", "voice.complete", "audio.read", "audio.store", "request.reserve", "answer.store", "gap.record", "job.reserve", "job.complete", "publication.read", "publication.recheck", "author.read", "proposal.store", "proposal.read", "proposal.apply", "qa.reserve", "qa.complete", "preview.reserve", "preview.complete", "rewrite.reserve", "rewrite.complete"];
const step = z.strictObject({
  id: z.string().regex(/^[a-z][a-z0-9-]*(\.[a-z][a-z0-9-]*)*$/),
  tool: z.enum(tools).optional(),
});
const task = z.strictObject({
  skills: z.array(z.enum(names)).min(1),
  tools: z.array(z.enum(tools)),
  steps: z.array(step).min(1),
});
const schema = z.strictObject({ id: z.literal("yeobek"), version: z.string().regex(/^\d+\.\d+\.\d+$/),
  instructions: z.literal("instructions.md"), messages: z.literal("messages.json"), skills: z.array(z.enum(names)).length(names.length),
  playbooks: z.strictObject({ "material-read": task, "ops-notify": task, "ops-support-reply": task, "visitor-transcribe": task, "visitor-speech": task, "narration-audio": task, "visitor-answer": task, "narration-draft": task, "narration-evaluate": task, "artist-organize": task, "artist-apply": task, "expected-qa-draft": task, "artist-preview": task, "artist-qa-rewrite": task }) });
const normalize = text => text.replace(/\r\n?/g, "\n").trimEnd() + "\n";
const read = path => normalize(readFileSync(new URL(path, root), "utf8"));
export function validateManifest(input) {
  const manifest = schema.parse(input);
  if (new Set(manifest.skills).size !== names.length) throw new Error("Duplicate plugin skill");
  const capabilities = { "material-read": [], "ops-support-reply": ["support.read"], "ops-notify": ["status.read"],
    "visitor-transcribe": ["voice.reserve", "voice.complete"], "visitor-speech": ["voice.read", "voice.store", "voice.reserve", "voice.complete"], "narration-audio": ["job.reserve", "audio.read", "audio.store", "job.complete"], "visitor-answer": ["request.reserve", "answer.store", "gap.record", "publication.read", "publication.recheck"], "narration-draft": ["author.read", "job.reserve", "job.complete"], "narration-evaluate": ["author.read"],
    "artist-organize": ["author.read", "proposal.store", "job.reserve", "job.complete"], "artist-apply": ["author.read", "proposal.read", "proposal.apply"],
    "expected-qa-draft": ["qa.reserve", "qa.complete"], "artist-preview": ["preview.reserve", "preview.complete"],
    "artist-qa-rewrite": ["rewrite.reserve", "rewrite.complete"] };
  for (const [name, playbook] of Object.entries(manifest.playbooks)) {
    if (new Set(playbook.skills).size !== playbook.skills.length || new Set(playbook.tools).size !== playbook.tools.length ||
      playbook.tools.some(tool => !capabilities[name].includes(tool))) throw new Error(`Invalid playbook capabilities: ${name}`);
    if (new Set(playbook.steps.map(({ id }) => id)).size !== playbook.steps.length) {
      throw new Error(`Duplicate playbook step: ${name}`);
    }
    if (playbook.steps.some(({ tool }) => tool && !playbook.tools.includes(tool))) {
      throw new Error(`Playbook step references an undeclared tool: ${name}`);
    }
  }
  return manifest;
}

export function compilePlugin() {
  const manifest = validateManifest(JSON.parse(read("plugin.json")));
  const skills = Object.fromEntries(manifest.skills.map(name => {
    const markdown = read(`skills/${name}/SKILL.md`);
    const match = /^---\nname: ([a-z-]+)\ndescription: ([^\n]+)\n---\n([\s\S]+)$/.exec(markdown);
    if (!match || match[1] !== name || markdown.length > 12000) throw new Error(`Invalid skill: ${name}`);
    return [name, { description: match[2], instructions: match[3].trim() }];
  }));
  const message = z.string().trim().min(1).max(600).refine(v => !v.includes("\u0000"));
  const messages = z.strictObject({ chooseOne: message, chooseArtwork: message, artworkUnavailable: message, noNarration: message,
    clarify: message, point: message, insufficient: message, gapRecorded: message, systemError: message }).parse(JSON.parse(read(manifest.messages)));
  const bundle = { ...manifest, instructions: read(manifest.instructions), messages, skills };
  const fingerprint = createHash("sha256").update(JSON.stringify(bundle)).digest("hex");
  return `// Generated by npm run ai:bundle; edit ai/yeobek instead.\nexport const yeobekPlugin = ${JSON.stringify({ ...bundle, fingerprint }, null, 2)} as const;\n`;
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const compiled = compilePlugin();
  if (process.argv.includes("--check")) {
    if (normalize(readFileSync(target, "utf8")) !== compiled) { console.error("AI plugin bundle is stale. Run npm run ai:bundle."); process.exitCode = 1; }
    else console.log("AI plugin bundle is current.");
  } else { writeFileSync(target, compiled); console.log("Built Yeobek product plugin."); }
}
